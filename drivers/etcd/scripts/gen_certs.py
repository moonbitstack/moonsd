"""Write src/client/fixtures_wbtest.mbt: the certificates the transport tests handshake with.

A root, two server certificates under it — one naming `localhost` by DNS and by address, one
naming it by DNS alone, so a client that dials the address and a client that names the host can
be told apart — a client certificate for mutual TLS, and a second root that trusts nothing here.

Issued by Python's `cryptography` (OpenSSL); rerun after changing a fixture.
"""

import datetime as dt
import ipaddress
import pathlib

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.x509.oid import ExtendedKeyUsageOID, NameOID

OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "client" / "fixtures_wbtest.mbt"
START = dt.datetime(2020, 1, 1, tzinfo=dt.timezone.utc)
END = dt.datetime(2040, 1, 1, tzinfo=dt.timezone.utc)


def name(cn):
    return x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, cn)])


def root(cn):
    key = ec.generate_private_key(ec.SECP256R1())
    cert = (x509.CertificateBuilder()
            .subject_name(name(cn)).issuer_name(name(cn))
            .public_key(key.public_key())
            .serial_number(x509.random_serial_number())
            .not_valid_before(START).not_valid_after(END)
            .add_extension(x509.BasicConstraints(ca=True, path_length=None), critical=True)
            .add_extension(x509.KeyUsage(
                digital_signature=False, content_commitment=False, key_encipherment=False,
                data_encipherment=False, key_agreement=False, key_cert_sign=True,
                crl_sign=True, encipher_only=False, decipher_only=False), critical=True)
            .sign(key, hashes.SHA256()))
    return cert, key


def server_leaf(issuer, key, names, cn="localhost"):
    issuer_cert, issuer_key = issuer
    cert = (x509.CertificateBuilder()
            .subject_name(name(cn)).issuer_name(issuer_cert.subject)
            .public_key(key.public_key())
            .serial_number(x509.random_serial_number())
            .not_valid_before(START).not_valid_after(END)
            .add_extension(x509.SubjectAlternativeName(names), critical=False)
            .add_extension(x509.ExtendedKeyUsage([ExtendedKeyUsageOID.SERVER_AUTH]),
                          critical=False)
            .sign(issuer_key, hashes.SHA256()))
    return cert


def client_leaf(issuer):
    issuer_cert, issuer_key = issuer
    key = ec.generate_private_key(ec.SECP256R1())
    cert = (x509.CertificateBuilder()
            .subject_name(name("moonetcd test client")).issuer_name(issuer_cert.subject)
            .public_key(key.public_key())
            .serial_number(x509.random_serial_number())
            .not_valid_before(START).not_valid_after(END)
            .add_extension(x509.SubjectAlternativeName([x509.DNSName("localhost")]),
                           critical=False)
            .add_extension(x509.ExtendedKeyUsage([ExtendedKeyUsageOID.CLIENT_AUTH]),
                           critical=False)
            .sign(issuer_key, hashes.SHA256()))
    return cert, key


def pem(cert):
    return cert.public_bytes(serialization.Encoding.PEM).decode().strip()


def key_pem(key):
    return key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
                             serialization.NoEncryption()).decode().strip()


def main():
    ca = root("moonetcd test root")
    server_key = ec.generate_private_key(ec.SECP256R1())
    both = server_leaf(ca, server_key, [
        x509.DNSName("localhost"), x509.IPAddress(ipaddress.ip_address("127.0.0.1"))])
    named = server_leaf(ca, server_key, [x509.DNSName("localhost")])
    client_cert, client_key = client_leaf(ca)
    values = {
        "root": pem(ca[0]),
        "other_root": pem(root("unrelated root")[0]),
        "server_cert": pem(both),
        "named_cert": pem(named),
        "server_key": key_pem(server_key),
        "client_cert": pem(client_cert),
        "client_key": key_pem(client_key),
    }
    out = ["// Generated by scripts/gen_certs.py; rerun it rather than editing.", ""]
    for k, v in values.items():
        out.append("///|")
        out.append(f"let {k} : String =")
        out.extend("  #|" + line for line in v.split("\n"))
        out.append("")
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {len(values)} values to {OUT}")


if __name__ == "__main__":
    main()
